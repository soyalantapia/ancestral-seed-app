/**
 * Datos de países latinoamericanos para el formulario de certificación.
 *
 * Cada país trae:
 *  - flag: emoji de bandera (no requiere assets).
 *  - dialCode: prefijo telefónico internacional (se autocompleta al
 *    elegir el país en el form).
 *  - subdivisionLabel: cómo se llama la división de 1er nivel en ese
 *    país (Provincia / Departamento / Estado / Región) — el label del
 *    campo se adapta para que SIEMPRE sea el término correcto.
 *  - subdivisions: lista de divisiones de 1er nivel (orden alfabético).
 *  - documentTypes: tipos de documento típicos del país.
 */
